export function normalizeRendererLocale(value) {
  const raw = String(value || "en").trim().toLowerCase();
  if (raw.startsWith("uz")) return "uz-Latn";
  if (raw.startsWith("ru")) return "ru-RU";
  return "en";
}

export function resolveProposalRendererLocale(proposalModel = {}, semanticModel = {}) {
  return normalizeRendererLocale(
    proposalModel?.brief?.locale
      || proposalModel?.brief?.sourceLanguage
      || proposalModel?.sourceLanguage
      || semanticModel?.project?.locale
      || semanticModel?.sourceLanguage
      || "en",
  );
}

export function rendererIntlLocale(locale) {
  const normalized = normalizeRendererLocale(locale);
  return normalized === "ru-RU" ? "ru-RU" : normalized === "uz-Latn" ? "uz-Latn-UZ" : "en-US";
}

